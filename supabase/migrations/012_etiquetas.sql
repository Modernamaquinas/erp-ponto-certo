-- Etiquetas de produto (impressora térmica Elgin L42, linguagem PPLA). Roda também no PGlite; permissões em 013.
-- Modelos vêm do DirectControl (ETIQUETAS_PERSONALIZADAS / ETIQUETAS_CAMPOS) com os mesmos códigos; a
-- sincronização só acrescenta modelos novos e não desfaz ajustes feitos no ERP.
-- Posições em centésimos de polegada (0,01" = 0,254 mm), medidas a partir da base (linha) e da esquerda.

create table etiqueta_modelos (
  id            int primary key generated by default as identity (start with 1000000),
  descricao     text not null,
  linguagem     text not null default 'PPLA' check (linguagem in ('PPLA', 'PPLB', 'LASER')),
  temperatura   int not null default 10,        -- comando Hnn (queima)
  pixel         text not null default 'D11',    -- comando Dxx (tamanho do ponto)
  avanco        int not null default 320,       -- comando f (posição de corte/destaque)
  padrao        boolean not null default false,
  ativo         boolean not null default true,
  origem        text not null default 'erp' check (origem in ('erp', 'legado')),
  atualizado_em timestamptz not null default now()
);
create unique index etiqueta_modelos_um_padrao on etiqueta_modelos (padrao) where padrao;

create table etiqueta_campos (
  id              int primary key generated by default as identity (start with 1000000),
  modelo_id       int not null references etiqueta_modelos(id) on delete cascade,
  coluna          int not null default 1,       -- coluna da etiqueta no rolo (1..n)
  orientacao      text not null default '1',    -- 1 normal, 2/3/4 girada
  fonte           text not null,                -- 0-9 texto; letra = código de barras (E = Code 128)
  mult_h          text not null default '1',    -- multiplicador horizontal (ou barra larga)
  mult_v          text not null default '1',    -- multiplicador vertical (ou barra estreita)
  subtipo         text not null default '000',  -- tamanho da fonte 9 ou altura do código de barras
  linha           int not null,
  esquerda        int not null,
  texto           text not null,                -- com variáveis [NOME_PROD] [PRECO] [COD_BARRAS] ...
  max_caracteres  int,
  ordem           int
);
create index etiqueta_campos_modelo on etiqueta_campos (modelo_id, coluna);

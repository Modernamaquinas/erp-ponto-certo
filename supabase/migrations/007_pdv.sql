-- ERP Ponto Certo — PDV (vendas no balcão) e orçamentos, com operador identificado por código de 4 dígitos.
-- Roda também no PGlite; RLS em 008_pdv_seguranca.sql. Venda e orçamento são gravados só pela API (service role),
-- que confere o código do operador e as permissões dele.

create table operadores (
  id                   int primary key generated by default as identity,
  codigo               text not null unique check (codigo ~ '^\d{4}$'),
  nome                 text not null,
  usuario_legado_id    int,                       -- vendedor/usuário correspondente no DirectControl
  ativo                boolean not null default true,
  desconto_maximo      numeric(5,2) not null default 0 check (desconto_maximo between 0 and 100),  -- % sobre a venda
  vende_sem_estoque    boolean not null default false,
  vende_abaixo_custo   boolean not null default false,
  converte_orcamento   boolean not null default true,
  criado_em            timestamptz not null default now(),
  atualizado_em        timestamptz not null default now()
);
create trigger operadores_toca before update on operadores for each row execute function toca_atualizado_em();

alter table vendas add column origem text not null default 'legado' check (origem in ('legado', 'erp'));
alter table vendas add column operador_id int references operadores(id);
alter table vendas add column vendedor_legado int;
alter table vendas add column criado_em timestamptz default now();

create table orcamentos (
  id               bigint primary key generated by default as identity (start with 1000000),
  data             date not null,
  hora             time,
  cliente_id       bigint references clientes(id),
  cliente_nome     text,
  operador_id      int references operadores(id),
  vendedor_legado  int,
  status           text not null default 'aberto' check (status in ('aberto', 'convertido', 'cancelado')),
  validade         date,
  total_produtos   numeric(14,2) not null default 0,
  desconto         numeric(14,2) not null default 0,
  total            numeric(14,2) not null default 0,
  observacao       text,
  venda_id         bigint references vendas(id),
  origem           text not null default 'erp' check (origem in ('legado', 'erp')),
  criado_em        timestamptz not null default now(),
  atualizado_em    timestamptz not null default now()
);
create index orcamentos_data on orcamentos (data desc);
create index orcamentos_cliente on orcamentos (cliente_id);
create trigger orcamentos_toca before update on orcamentos for each row execute function toca_atualizado_em();
alter table vendas add column orcamento_id bigint references orcamentos(id);

create table orcamento_itens (
  orcamento_id    bigint not null references orcamentos(id) on delete cascade,
  item            int not null,
  produto_id      bigint references produtos(id),
  descricao       text,
  quantidade      numeric(14,3) not null,
  preco_unitario  numeric(14,4) not null,
  desconto        numeric(14,2) not null default 0,
  total           numeric(14,2) not null,
  primary key (orcamento_id, item)
);

-- forma do PDV -> formas_pagamento herdadas do DirectControl
create or replace function forma_pagamento_pdv(p_forma text) returns int
language sql immutable as $$
  select case p_forma when 'dinheiro' then 2 when 'cheque' then 5 when 'credito' then 7 when 'debito' then 8
    when 'pix' then 13 when 'crediario' then 14 when 'boleto' then 18 when 'sem_pagamento' then 12 else null end
$$;

/** Confere itens, permissões, estoque e desconto. Usada pela venda e pelo orçamento. */
create or replace function pdv_validar_itens(p_op operadores, p jsonb, p_conferir_estoque boolean)
returns table (total_produtos numeric, desconto_total numeric, total numeric)
language plpgsql as $$
declare it jsonb; pr record; v_q numeric; v_pu numeric; v_desc numeric; v_bruto numeric;
        v_tp numeric := 0; v_di numeric := 0; v_dg numeric := round(coalesce((p->>'desconto_geral')::numeric, 0), 2);
begin
  if jsonb_array_length(coalesce(p->'itens', '[]')) = 0 then raise exception 'Inclua pelo menos um produto'; end if;
  for it in select * from jsonb_array_elements(p->'itens') loop
    select id, nome, ativo, estoque, coalesce(custo_medio, custo, 0) as custo into pr from produtos where id = (it->>'produto_id')::bigint;
    if pr.id is null then raise exception 'Produto % não encontrado', it->>'produto_id'; end if;
    v_q := (it->>'quantidade')::numeric; v_pu := (it->>'preco_unitario')::numeric; v_desc := round(coalesce((it->>'desconto')::numeric, 0), 2);
    if not pr.ativo then raise exception 'Produto inativo: %', pr.nome; end if;
    if v_q is null or v_q <= 0 then raise exception 'Quantidade inválida em %', pr.nome; end if;
    if v_pu is null or v_pu <= 0 then raise exception 'Preço inválido em %', pr.nome; end if;
    v_bruto := round(v_q * v_pu, 2);
    if v_desc < 0 or v_desc >= v_bruto then raise exception 'Desconto inválido em %', pr.nome; end if;
    if not p_op.vende_abaixo_custo and pr.custo > 0 and (v_bruto - v_desc) / v_q < pr.custo then
      raise exception 'Preço abaixo do custo em % (operador sem permissão)', pr.nome;
    end if;
    if p_conferir_estoque and not p_op.vende_sem_estoque and pr.estoque < v_q then
      raise exception 'Estoque insuficiente de % (disponível: %)', pr.nome, trim(to_char(pr.estoque, 'FM999999990.###'));
    end if;
    v_tp := v_tp + v_bruto; v_di := v_di + v_desc;
  end loop;
  if v_dg < 0 or v_dg >= v_tp - v_di then raise exception 'Desconto geral inválido'; end if;
  if v_tp > 0 and (v_di + v_dg) / v_tp * 100 > p_op.desconto_maximo + 0.001 then
    raise exception 'Desconto de % %% acima do permitido para o operador (% %%)',
      trim(to_char((v_di + v_dg) / v_tp * 100, 'FM990.00')), trim(to_char(p_op.desconto_maximo, 'FM990.00'));
  end if;
  return query select v_tp, v_di + v_dg, v_tp - v_di - v_dg;
end $$;

create or replace function pdv_operador(p_codigo text) returns operadores
language plpgsql as $$
declare op operadores;
begin
  select * into op from operadores where codigo = p_codigo and ativo;
  if op.id is null then raise exception 'Código de operador inválido'; end if;
  return op;
end $$;

/**
 * Finaliza uma venda do PDV. p = { operador_codigo, cliente_id?, cliente_nome?, cpf?, observacao?, num_caixa?, orcamento_id?,
 *   desconto_geral?, itens: [{ produto_id, quantidade, preco_unitario, desconto? }],
 *   pagamentos: [{ forma, valor, parcelas?, primeiro_vencimento? }] }
 */
create or replace function finalizar_venda(p jsonb) returns bigint
language plpgsql as $$
declare op operadores; tot record; v_id bigint; it jsonb; pg jsonb; pr record; i int := 0; j int := 0; n int; k int;
        v_pago numeric := 0; v_troco numeric; v_cli_id bigint; v_cli_nome text; v_cli_bloq boolean; v_agora timestamp := now() at time zone 'America/Sao_Paulo';
        v_hoje date := (now() at time zone 'America/Sao_Paulo')::date; v_parc numeric; v_venc date; v_valor numeric;
        v_tem_dinheiro boolean := false;
begin
  op := pdv_operador(p->>'operador_codigo');
  select * into tot from pdv_validar_itens(op, p, true);

  if jsonb_array_length(coalesce(p->'pagamentos', '[]')) = 0 then raise exception 'Informe a forma de pagamento'; end if;
  for pg in select * from jsonb_array_elements(p->'pagamentos') loop
    if forma_pagamento_pdv(pg->>'forma') is null then raise exception 'Forma de pagamento inválida: %', pg->>'forma'; end if;
    if coalesce((pg->>'valor')::numeric, 0) <= 0 then raise exception 'Valor de pagamento inválido'; end if;
    v_pago := v_pago + round((pg->>'valor')::numeric, 2);
    if pg->>'forma' = 'dinheiro' then v_tem_dinheiro := true; end if;
    if pg->>'forma' = 'crediario' and (p->>'cliente_id') is null then raise exception 'Crediário exige cliente'; end if;
  end loop;
  if v_pago < tot.total then raise exception 'Pagamento (%) menor que o total (%)', v_pago, tot.total; end if;
  v_troco := v_pago - tot.total;
  if v_troco > 0 and not v_tem_dinheiro then raise exception 'Troco só é permitido com pagamento em dinheiro'; end if;

  if (p->>'cliente_id') is not null then
    select id, nome, bloqueado into v_cli_id, v_cli_nome, v_cli_bloq from clientes where id = (p->>'cliente_id')::bigint;
    if v_cli_id is null then raise exception 'Cliente não encontrado'; end if;
    if v_cli_bloq and exists (select 1 from jsonb_array_elements(p->'pagamentos') x where x->>'forma' = 'crediario') then
      raise exception 'Cliente bloqueado para crediário';
    end if;
  end if;

  insert into vendas (data, hora, cliente_id, cliente_nome, cpf_nota, total_produtos, desconto, total, situacao, num_caixa,
                      observacao, origem, operador_id, orcamento_id)
  values (v_hoje, v_agora::time, v_cli_id, coalesce(v_cli_nome, p->>'cliente_nome'), nullif(regexp_replace(coalesce(p->>'cpf', ''), '\D', '', 'g'), ''),
          tot.total_produtos, tot.desconto_total, tot.total, 'finalizada', (p->>'num_caixa')::int, p->>'observacao', 'erp', op.id,
          (p->>'orcamento_id')::bigint)
  returning id into v_id;

  for it in select * from jsonb_array_elements(p->'itens') loop
    i := i + 1;
    select id, nome, coalesce(custo_medio, custo) as custo into pr from produtos where id = (it->>'produto_id')::bigint for update;
    insert into venda_itens (venda_id, item, produto_id, descricao, quantidade, preco_unitario, desconto, total, custo)
    values (v_id, i, pr.id, pr.nome, (it->>'quantidade')::numeric, (it->>'preco_unitario')::numeric,
            round(coalesce((it->>'desconto')::numeric, 0), 2),
            round((it->>'quantidade')::numeric * (it->>'preco_unitario')::numeric, 2) - round(coalesce((it->>'desconto')::numeric, 0), 2), pr.custo);
    update produtos set estoque = estoque - (it->>'quantidade')::numeric, data_ultima_saida = v_hoje where id = pr.id;
  end loop;

  for pg in select * from jsonb_array_elements(p->'pagamentos') loop
    j := j + 1;
    v_valor := round((pg->>'valor')::numeric, 2);
    n := greatest(1, least(24, coalesce((pg->>'parcelas')::int, 1)));
    insert into venda_pagamentos (venda_id, item, forma_pagamento_id, valor, parcelas)
    values (v_id, j, forma_pagamento_pdv(pg->>'forma'), v_valor, n);
    if pg->>'forma' = 'crediario' then
      v_venc := coalesce((pg->>'primeiro_vencimento')::date, v_hoje + 30);
      for k in 1..n loop
        v_parc := case when k < n then round(v_valor / n, 2) else v_valor - round(v_valor / n, 2) * (n - 1) end;
        insert into contas_receber (cliente_id, venda_id, documento, historico, parcela, total_parcelas, emissao, vencimento,
                                    valor, saldo, status, baixa_replicada_legado)
        values (v_cli_id, v_id, v_id::text, 'VENDA N ' || v_id, k, n, v_hoje, (v_venc + make_interval(months => k - 1))::date,
                v_parc, v_parc, 'aberto', true);
      end loop;
    else
      insert into caixa_lancamentos (data, hora, historico, entrada, forma_pagamento_id, documento, origem, usuario)
      values (v_hoje, v_agora::time, 'RECEITA VENDA N ' || v_id || ' - ' || coalesce(v_cli_nome, 'AO CONSUMIDOR'), v_valor,
              forma_pagamento_pdv(pg->>'forma'), v_id::text, 'erp', op.nome);
    end if;
  end loop;
  if v_troco > 0 then
    insert into caixa_lancamentos (data, hora, historico, saida, forma_pagamento_id, documento, origem, usuario)
    values (v_hoje, v_agora::time, 'TROCO VENDA N ' || v_id, v_troco, 2, v_id::text, 'erp', op.nome);
  end if;

  if (p->>'orcamento_id') is not null then
    if not op.converte_orcamento then raise exception 'Operador sem permissão para converter orçamento'; end if;
    update orcamentos set status = 'convertido', venda_id = v_id where id = (p->>'orcamento_id')::bigint and status = 'aberto';
    if not found then raise exception 'Orçamento não está aberto'; end if;
  end if;
  return v_id;
end $$;

/** Cria (sem id) ou atualiza (com id, se aberto) um orçamento. Não mexe no estoque. */
create or replace function salvar_orcamento(p jsonb) returns bigint
language plpgsql as $$
declare op operadores; tot record; v_id bigint := (p->>'id')::bigint; it jsonb; i int := 0; v_cli_id bigint; v_cli_nome text;
begin
  op := pdv_operador(p->>'operador_codigo');
  select * into tot from pdv_validar_itens(op, p, false);
  if (p->>'cliente_id') is not null then select id, nome into v_cli_id, v_cli_nome from clientes where id = (p->>'cliente_id')::bigint; end if;
  if v_id is null then
    insert into orcamentos (data, hora, cliente_id, cliente_nome, operador_id, validade, total_produtos, desconto, total, observacao)
    values ((now() at time zone 'America/Sao_Paulo')::date, (now() at time zone 'America/Sao_Paulo')::time, v_cli_id,
            coalesce(v_cli_nome, p->>'cliente_nome'), op.id, (p->>'validade')::date, tot.total_produtos, tot.desconto_total, tot.total,
            p->>'observacao')
    returning id into v_id;
  else
    update orcamentos set cliente_id = v_cli_id, cliente_nome = coalesce(v_cli_nome, p->>'cliente_nome'), operador_id = op.id,
           validade = (p->>'validade')::date, total_produtos = tot.total_produtos, desconto = tot.desconto_total, total = tot.total,
           observacao = p->>'observacao'
     where id = v_id and status = 'aberto';
    if not found then raise exception 'Orçamento não está aberto'; end if;
    delete from orcamento_itens where orcamento_id = v_id;
  end if;
  for it in select * from jsonb_array_elements(p->'itens') loop
    i := i + 1;
    insert into orcamento_itens (orcamento_id, item, produto_id, descricao, quantidade, preco_unitario, desconto, total)
    select v_id, i, pr.id, pr.nome, (it->>'quantidade')::numeric, (it->>'preco_unitario')::numeric, round(coalesce((it->>'desconto')::numeric, 0), 2),
           round((it->>'quantidade')::numeric * (it->>'preco_unitario')::numeric, 2) - round(coalesce((it->>'desconto')::numeric, 0), 2)
      from produtos pr where pr.id = (it->>'produto_id')::bigint;
  end loop;
  return v_id;
end $$;

-- ---------------------------------------------------------------- operações financeiras
-- Baixa (total ou parcial) de uma conta a receber feita no ERP.
create or replace function baixar_conta_receber(
  p_id bigint, p_valor numeric, p_data date, p_forma_id int, p_usuario text default null
) returns contas_receber
language plpgsql as $$
declare
  c contas_receber;
  f text;
begin
  select * into c from contas_receber where id = p_id for update;
  if not found then raise exception 'Conta a receber % não encontrada', p_id; end if;
  if c.status <> 'aberto' then raise exception 'Conta % não está em aberto', p_id; end if;
  if p_valor is null or p_valor <= 0 then raise exception 'Valor da baixa deve ser positivo'; end if;
  if p_valor > c.saldo then raise exception 'Valor (%) maior que o saldo (%)', p_valor, c.saldo; end if;

  select descricao into f from formas_pagamento where id = p_forma_id;
  insert into recebimentos (conta_receber_id, data, forma_pagamento_id, forma_descricao, valor, origem, usuario)
  values (p_id, p_data, p_forma_id, f, p_valor, 'erp', p_usuario);

  update contas_receber set
    valor_pago = valor_pago + p_valor,
    saldo = saldo - p_valor,
    status = case when saldo - p_valor <= 0 then 'pago' else 'aberto' end,
    data_pagamento = case when saldo - p_valor <= 0 then p_data else data_pagamento end,
    baixa_origem = 'erp',
    baixa_replicada_legado = false
  where id = p_id
  returning * into c;
  return c;
end $$;

create or replace function baixar_conta_pagar(
  p_id bigint, p_valor numeric, p_data date, p_observacao text default null
) returns contas_pagar
language plpgsql as $$
declare
  c contas_pagar;
begin
  select * into c from contas_pagar where id = p_id for update;
  if not found then raise exception 'Conta a pagar % não encontrada', p_id; end if;
  if c.status <> 'aberto' then raise exception 'Conta % não está em aberto', p_id; end if;
  if p_valor is null or p_valor <= 0 then raise exception 'Valor da baixa deve ser positivo'; end if;
  if p_valor > c.saldo then raise exception 'Valor (%) maior que o saldo (%)', p_valor, c.saldo; end if;

  update contas_pagar set
    valor_pago = valor_pago + p_valor,
    saldo = saldo - p_valor,
    status = case when saldo - p_valor <= 0 then 'pago' else 'aberto' end,
    data_pagamento = case when saldo - p_valor <= 0 then p_data else data_pagamento end,
    baixa_origem = 'erp',
    conferir_baixa_legado = false,
    observacao = coalesce(p_observacao, observacao)
  where id = p_id
  returning * into c;
  return c;
end $$;

-- Baixa em lote das contas a pagar herdadas sem baixa (vencidas até p_ate), pela data de vencimento.
create or replace function baixar_pagar_legado_em_lote(p_ate date) returns int
language plpgsql as $$
declare
  n int;
begin
  update contas_pagar set
    valor_pago = valor_pago + saldo,
    data_pagamento = vencimento,
    saldo = 0,
    status = 'pago',
    baixa_origem = 'erp',
    conferir_baixa_legado = false,
    observacao = concat_ws(' | ', observacao, 'Baixa em lote: herdada do DirectControl sem baixa')
  where conferir_baixa_legado and status = 'aberto' and vencimento <= p_ate;
  get diagnostics n = row_count;
  return n;
end $$;

-- Confirmação de pagamento de uma cobrança Asaas: baixa todos os títulos dela (idempotente).
create or replace function confirmar_cobranca_paga(
  p_asaas_id text, p_data date, p_valor_pago numeric, p_valor_liquido numeric, p_tipo text
) returns cobrancas
language plpgsql as $$
declare
  cb cobrancas;
  t contas_receber;
begin
  select * into cb from cobrancas where asaas_payment_id = p_asaas_id for update;
  if not found then raise exception 'Cobrança Asaas % não encontrada', p_asaas_id; end if;
  if cb.status = 'paga' then return cb; end if;

  for t in select * from contas_receber where id = any(cb.titulos) and status = 'aberto' for update loop
    insert into recebimentos (conta_receber_id, data, forma_descricao, valor, origem, usuario)
    values (t.id, p_data, 'ASAAS ' || coalesce(p_tipo, ''), t.saldo, 'asaas', 'asaas');
    update contas_receber set
      valor_pago = valor_pago + saldo,
      saldo = 0,
      status = 'pago',
      data_pagamento = p_data,
      baixa_origem = 'asaas',
      baixa_replicada_legado = false
    where id = t.id;
  end loop;

  update cobrancas set
    status = 'paga', data_pagamento = p_data, valor_pago = p_valor_pago,
    valor_liquido = p_valor_liquido, tipo_pagamento = p_tipo
  where id = cb.id
  returning * into cb;
  return cb;
end $$;

-- ---------------------------------------------------------------- visões
create or replace view v_receber_por_cliente as
select
  c.id as cliente_id, c.nome, c.cpf_cnpj,
  coalesce(c.celular_cobranca, c.celular) as celular,
  coalesce(c.email_cobranca, c.email) as email,
  count(*) as titulos,
  sum(r.saldo) as saldo,
  sum(r.saldo) filter (where r.vencimento < current_date) as atrasado,
  min(r.vencimento) as proximo_vencimento,
  count(*) filter (where r.cobranca_id is null) as sem_cobranca
from contas_receber r
join clientes c on c.id = r.cliente_id
where r.status = 'aberto'
group by c.id;

-- Títulos que ainda estão numa cobrança Asaas pendente mas já foram pagos no balcão (DirectControl):
-- a cobrança precisa ser cancelada no Asaas para o cliente não pagar duas vezes.
create or replace view v_cobrancas_conflito as
select cb.id as cobranca_id, cb.asaas_payment_id, cb.cliente_id, c.nome, cb.valor, cb.vencimento,
       array_agg(r.id) as titulos_pagos_no_balcao
from cobrancas cb
join contas_receber r on r.id = any(cb.titulos)
join clientes c on c.id = cb.cliente_id
where cb.status in ('pendente', 'vencida') and r.status = 'pago' and r.baixa_origem = 'legado'
group by cb.id, c.nome;

create or replace function resumo_painel() returns json
language sql stable as $$
  select json_build_object(
    'receber_aberto',   (select coalesce(sum(saldo), 0) from contas_receber where status = 'aberto'),
    'receber_atrasado', (select coalesce(sum(saldo), 0) from contas_receber where status = 'aberto' and vencimento < current_date),
    'clientes_devendo', (select count(distinct cliente_id) from contas_receber where status = 'aberto'),
    'pagar_7_dias',     (select coalesce(sum(saldo), 0) from contas_pagar where status = 'aberto' and not conferir_baixa_legado
                           and vencimento between current_date and current_date + 7),
    'pagar_atrasado',   (select coalesce(sum(saldo), 0) from contas_pagar where status = 'aberto' and not conferir_baixa_legado
                           and vencimento < current_date),
    'pagar_conferir',   (select count(*) from contas_pagar where conferir_baixa_legado and status = 'aberto'),
    'vendas_hoje',      (select coalesce(sum(total), 0) from vendas where situacao = 'finalizada' and data = current_date),
    'vendas_mes',       (select coalesce(sum(total), 0) from vendas where situacao = 'finalizada'
                           and data >= date_trunc('month', current_date)),
    'vendas_mes_qtd',   (select count(*) from vendas where situacao = 'finalizada' and data >= date_trunc('month', current_date)),
    'cobrancas_pendentes', (select coalesce(sum(valor), 0) from cobrancas where status in ('pendente', 'vencida')),
    'cobrancas_pagas_mes', (select coalesce(sum(valor_pago), 0) from cobrancas where status = 'paga'
                           and data_pagamento >= date_trunc('month', current_date)),
    'baixas_a_replicar', (select count(*) from contas_receber where not baixa_replicada_legado),
    'conflitos',        (select count(*) from v_cobrancas_conflito),
    'ultima_sincronizacao', (select max(fim) from sincronizacoes where erro is null)
  )
$$;

-- Vendas finalizadas por mês (gráfico do painel).
create or replace function vendas_por_mes(p_meses int default 12) returns table (mes date, total numeric, qtd bigint)
language sql stable as $$
  select date_trunc('month', data)::date, sum(total), count(*)
  from vendas
  where situacao = 'finalizada' and data >= (date_trunc('month', current_date) - make_interval(months => p_meses - 1))
  group by 1 order by 1
$$;

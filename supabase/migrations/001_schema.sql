-- ERP Ponto Certo — esquema principal (Fase 1)
-- Os códigos do DirectControl são mantidos como `id` (cliente 2026 continua sendo 2026).
-- Registros criados no ERP recebem ids a partir de 1.000.000, sem colisão com o legado.

create extension if not exists pg_trgm;

-- Normaliza texto para busca (minúsculo, sem acento) — sem depender da extensão unaccent.
create or replace function normaliza_busca(t text) returns text
language sql immutable as $$
  select lower(translate(coalesce(t, ''),
    'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑáàâãäéèêëíìîïóòôõöúùûüçñ',
    'AAAAAEEEEIIIIOOOOOUUUUCNaaaaaeeeeiiiiooooouuuucn'))
$$;

create or replace function toca_atualizado_em() returns trigger
language plpgsql as $$
begin
  new.atualizado_em := now();
  return new;
end $$;


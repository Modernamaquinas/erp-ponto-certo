-- ERP Ponto Certo — cartões e PIX pelo TEF (PayGo Web, multi-adquirente: Cielo, Stone, PagSeguro, Vero, Shipay).
-- Fase 1: histórico do DirectControl (TEF_TRANSACAO) + taxas e previsão de recebimento.
-- Fase 2: o PDV do ERP grava aqui as transações aprovadas pelo agente TEF do caixa (origem = 'erp').
-- Roda também no PGlite (testes); o RLS fica em 004_cartoes_seguranca.sql.

create table tef_transacoes (
  id               bigint primary key generated by default as identity (start with 1000000),
  venda_id         bigint references vendas(id) on delete set null,
  operacao         text not null default 'venda' check (operacao in ('venda', 'cancelamento')),
  situacao         text not null check (situacao in ('aprovada', 'nao_concluida', 'cancelada')),
  gerenciador      text not null default 'paygo',
  rede             text,                 -- adquirente: CIELO, STONE, PAGSEGURO, VERO, SHIPAY…
  modalidade       text check (modalidade in ('credito', 'credito_parcelado_loja', 'credito_parcelado_adm',
                                              'debito', 'pix', 'voucher', 'outro')),
  bandeira         text,
  parcelas         int not null default 1 check (parcelas >= 1),
  valor            numeric(14,2) not null default 0,
  nsu              text,
  autorizacao      text,
  cnpj_adquirente  text,
  data_hora        timestamp,
  data             date generated always as (data_hora::date) stored,
  mensagem         text,                 -- texto do gerenciador (ex.: "OPERAÇÃO CANCELADA")
  comprovante      text,                 -- via do cliente/estabelecimento (Fase 2)
  transacao_original_id bigint references tef_transacoes(id),  -- em um cancelamento
  origem           text not null default 'legado' check (origem in ('legado', 'erp')),
  criado_em        timestamptz not null default now()
);
create index tef_transacoes_data on tef_transacoes (data);
create index tef_transacoes_rede_data on tef_transacoes (rede, data);
create index tef_transacoes_venda on tef_transacoes (venda_id);

-- Taxa (MDR) e prazo de cada adquirente. A faixa que vale é a de menor `parcelas_ate` que cobre a transação.
create table cartao_taxas (
  id               int primary key generated by default as identity,
  rede             text not null,
  modalidade       text not null check (modalidade in ('credito', 'credito_parcelado_loja', 'credito_parcelado_adm',
                                                       'debito', 'pix', 'voucher', 'outro')),
  parcelas_ate     int not null default 1 check (parcelas_ate between 1 and 24),
  taxa_percentual  numeric(6,3) not null check (taxa_percentual >= 0 and taxa_percentual < 100),
  dias_recebimento int not null check (dias_recebimento between 0 and 400),
  atualizado_em    timestamptz not null default now(),
  unique (rede, modalidade, parcelas_ate)
);
create trigger cartao_taxas_toca before update on cartao_taxas for each row execute function toca_atualizado_em();

-- Prazo padrão enquanto a taxa não foi cadastrada (o valor líquido fica nulo = "sem taxa").
create or replace function prazo_padrao_cartao(p_modalidade text) returns int
language sql immutable as $$
  select case p_modalidade when 'pix' then 0 when 'debito' then 1 when 'voucher' then 30 else 30 end
$$;

-- Um recebível por parcela. Crédito parcelado pela loja cai mês a mês; pela administradora, de uma vez.
create view v_cartoes_recebiveis as
select t.id as transacao_id, t.venda_id, t.data, t.rede, t.modalidade, t.bandeira, t.parcelas, p.n as parcela, q.qt as total_parcelas,
       r.bruto as valor_bruto, tx.taxa_percentual,
       case when tx.taxa_percentual is null then null else round(r.bruto * (1 - tx.taxa_percentual / 100), 2) end as valor_liquido,
       t.data + coalesce(tx.dias_recebimento, prazo_padrao_cartao(t.modalidade)) + 30 * (p.n - 1) as previsao
from tef_transacoes t
cross join lateral (select case when t.modalidade = 'credito_parcelado_loja' then t.parcelas else 1 end as qt) q
cross join lateral generate_series(1, q.qt) as p(n)
-- a 1ª parcela absorve a diferença de centavos
cross join lateral (select round(t.valor / q.qt, 2)
                      + case when p.n = 1 then t.valor - round(t.valor / q.qt, 2) * q.qt else 0 end as bruto) r
left join lateral (
  select c.taxa_percentual, c.dias_recebimento from cartao_taxas c
  where c.rede = t.rede and c.modalidade = t.modalidade and c.parcelas_ate >= t.parcelas
  order by c.parcelas_ate limit 1
) tx on true
where t.situacao = 'aprovada' and t.operacao = 'venda' and t.data is not null;

-- Fase 2: o PDV registra o que o agente TEF devolveu. Cancelamento aprovado marca a original.
create or replace function registrar_transacao_tef(p jsonb) returns bigint
language plpgsql as $$
declare v_id bigint; v_original bigint;
begin
  if coalesce(p->>'situacao', '') not in ('aprovada', 'nao_concluida') then
    raise exception 'Situação inválida: %', p->>'situacao';
  end if;
  if (p->>'operacao') = 'cancelamento' then
    v_original := (p->>'transacao_original_id')::bigint;
    if v_original is null or not exists (select 1 from tef_transacoes where id = v_original and situacao = 'aprovada') then
      raise exception 'Transação original não encontrada ou já cancelada';
    end if;
  end if;
  insert into tef_transacoes (venda_id, operacao, situacao, gerenciador, rede, modalidade, bandeira, parcelas, valor,
                              nsu, autorizacao, cnpj_adquirente, data_hora, mensagem, comprovante, transacao_original_id, origem)
  values ((p->>'venda_id')::bigint, coalesce(p->>'operacao', 'venda'), p->>'situacao', coalesce(p->>'gerenciador', 'paygo'),
          upper(p->>'rede'), p->>'modalidade', upper(p->>'bandeira'), greatest(coalesce((p->>'parcelas')::int, 1), 1),
          coalesce((p->>'valor')::numeric, 0), p->>'nsu', p->>'autorizacao', p->>'cnpj_adquirente',
          coalesce((p->>'data_hora')::timestamp, (now() at time zone 'America/Sao_Paulo')), p->>'mensagem', p->>'comprovante',
          v_original, 'erp')
  returning id into v_id;
  if v_original is not null and (p->>'situacao') = 'aprovada' then
    update tef_transacoes set situacao = 'cancelada' where id = v_original;
  end if;
  return v_id;
end $$;
